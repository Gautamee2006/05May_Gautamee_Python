# How to check the type of a variable dynamically using type().

student_name = "Gautamee"
student_age = 20
fees = 5000.75
is_active = True

print("Value :", student_name)
print("Type :", type(student_name))

print("Value :", student_age)
print("Type :", type(student_age))

print("Value :", fees)
print("Type :", type(fees))

print("Value :", is_active)
print("Type :", type(is_active))